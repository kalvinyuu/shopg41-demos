import React, { useState, useEffect, useCallback } from "react"
import { createRoot } from "react-dom/client"

interface Product {
  id: number
  name: string
  price: number
  imageUrl?: string
  image_url?: string
}

interface AiCopy {
  id: number
  headline: string
  tagline: string
  keywords: string[]
}

function App() {
  const [products, setProducts] = useState<Product[]>([])
  const [copy, setCopy] = useState<Record<number, AiCopy>>({})
  const [loading, setLoading] = useState(false)
  const [status, setStatus] = useState("")

  const fetchProducts = useCallback(async () => {
    const res = await fetch("/api/products")
    setProducts(await res.json())
  }, [])

  useEffect(() => {
    fetchProducts()
  }, [fetchProducts])

  const handleGenerate = async () => {
    setLoading(true)
    setStatus("Calling shopG41 pipeline /api/e/ai-product-copy (query → ai → transform)…")
    try {
      const res = await fetch("/api/ai/copy")
      const data = await res.json()
      if (!res.ok) {
        setStatus(`Error: ${data.error || res.status}`)
        return
      }
      const byId: Record<number, AiCopy> = {}
      for (const item of Array.isArray(data) ? data : []) {
        byId[item.id] = item
      }
      setCopy(byId)
      setStatus("Done — copy generated by shopG41's AI pipeline step.")
    } catch (e) {
      setStatus(`Error: ${(e as Error).message}`)
    } finally {
      setLoading(false)
    }
  }

  return (
    <>
      <button onClick={handleGenerate} disabled={loading}>
        {loading ? "Generating…" : "Generate AI Marketing Copy"}
      </button>
      {status && <div className="status">{status}</div>}
      {status.includes("Error") && <div className="error">{status}</div>}

      <h2>Products ({products.length})</h2>
      {products.length === 0 && <p>No products yet. Add one below.</p>}

      <form
        onSubmit={async (e) => {
          e.preventDefault()
          const form = new FormData(e.currentTarget)
          await fetch("/api/products", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              name: form.get("name"),
              price: Number(form.get("price")),
            }),
          })
          await fetchProducts()
        }}
      >
        <input type="text" name="name" placeholder="Product name" required />
        <input type="number" name="price" step="0.01" min="0.01" placeholder="Price" required />
        <button type="submit">Add Product</button>
      </form>

      {products.map((p) => {
        const c = copy[p.id]
        return (
          <div key={p.id} className="card">
            <h3>{p.name}</h3>
            <p className="price">£{p.price.toFixed(2)}</p>
            {c && (
              <div className="copy">
                <p><strong>{c.headline}</strong></p>
                <p>{c.tagline}</p>
                <div className="keywords">
                  {c.keywords.map((k) => (
                    <span key={k} className="chip">{k}</span>
                  ))}
                </div>
              </div>
            )}
          </div>
        )
      })}
    </>
  )
}

const root = createRoot(document.getElementById("root")!)
root.render(<App />)
